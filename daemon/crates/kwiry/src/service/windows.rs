const TASK_NAME: &str = "Kwiry";
const TASK_MARKER: &str = "Managed by Kwiry (task schema 1)";
const SCHTASKS_EXE: &str = "schtasks.exe";
const RESTART_INTERVAL: &str = "PT1M";
const RESTART_COUNT: u8 = 3;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum TaskRegistration {
    Missing,
    Generated,
    Foreign,
}

pub(crate) struct WindowsTaskScheduler<R> {
    runner: R,
}

impl<R> WindowsTaskScheduler<R> {
    pub(crate) fn new(runner: R) -> Self {
        Self { runner }
    }
}

impl<R: CommandRunner> WindowsTaskScheduler<R> {
    fn run_schtasks(&self, operation: &str, args: &[OsString]) -> Result<CommandOutput> {
        self.runner
            .run(OsStr::new(SCHTASKS_EXE), args)
            .map_err(|_| anyhow!("could not execute {SCHTASKS_EXE} to {operation}"))
    }

    fn run_checked(&self, operation: &str, args: &[OsString]) -> Result<()> {
        let output = self.run_schtasks(operation, args)?;
        if output.code == Some(0) {
            Ok(())
        } else {
            Err(native_error(operation, &output))
        }
    }

    fn run_checked_allow_absent(&self, operation: &str, args: &[OsString]) -> Result<()> {
        let output = self.run_schtasks(operation, args)?;
        if output.code == Some(0) || is_missing_output(&output) || is_not_running_output(&output) {
            Ok(())
        } else {
            Err(native_error(operation, &output))
        }
    }

    fn inspect_registration(&self) -> Result<TaskRegistration> {
        let output =
            self.run_schtasks("inspect the scheduled task definition", &definition_args())?;
        if output.code == Some(0) {
            return Ok(if output.stdout.contains(TASK_MARKER) {
                TaskRegistration::Generated
            } else {
                TaskRegistration::Foreign
            });
        }
        if is_missing_output(&output) {
            return Ok(TaskRegistration::Missing);
        }
        Err(native_error(
            "inspect the scheduled task definition",
            &output,
        ))
    }

    fn query_status(&self) -> Result<ServiceStatus> {
        let output = self.run_schtasks("query the scheduled task", &query_args())?;
        if output.code == Some(0) {
            let (running, enabled) = parse_query_state(&output.stdout);
            let detail = if running {
                "Task Scheduler reports the task is running"
            } else if enabled {
                "Task Scheduler reports the task is stopped"
            } else {
                "Task Scheduler reports the task is disabled"
            };
            return Ok(ServiceStatus {
                manager: ServiceManagerKind::TaskScheduler,
                installed: true,
                enabled,
                running,
                detail: Some(detail.to_owned()),
            });
        }

        if is_missing_output(&output) {
            return Ok(ServiceStatus {
                manager: ServiceManagerKind::TaskScheduler,
                installed: false,
                enabled: false,
                running: false,
                detail: Some("Kwiry scheduled task is not registered".to_owned()),
            });
        }

        Err(native_error("query the scheduled task", &output))
    }
}

impl<R: CommandRunner> ServiceManager for WindowsTaskScheduler<R> {
    fn kind(&self) -> ServiceManagerKind {
        ServiceManagerKind::TaskScheduler
    }

    fn definition_matches(&self, spec: &ServiceSpec) -> Result<bool> {
        spec.validate()?;
        let output =
            self.run_schtasks("inspect the scheduled task definition", &definition_args())?;
        if is_missing_output(&output) {
            return Ok(false);
        }
        if output.code != Some(0) {
            return Err(native_error(
                "inspect the scheduled task definition",
                &output,
            ));
        }
        if !output.stdout.contains(TASK_MARKER) {
            bail!("refusing to inspect a scheduled task not generated by Kwiry: {TASK_NAME}");
        }
        let (executable, arguments) = task_action_fields(spec)?;
        Ok(output
            .stdout
            .contains(&format!("<Command>{}</Command>", xml_escape(executable)))
            && output.stdout.contains(&format!(
                "<Arguments>{}</Arguments>",
                xml_escape(&arguments)
            )))
    }

    fn install(&self, spec: &ServiceSpec) -> Result<()> {
        if self.inspect_registration()? == TaskRegistration::Foreign {
            bail!("refusing to replace a scheduled task not generated by Kwiry: {TASK_NAME}");
        }

        #[cfg(windows)]
        let sid = current_user_sid()?;
        #[cfg(not(windows))]
        let sid = non_windows_sid_error()?;

        let xml = render_task_xml(spec, &sid)?;
        with_temporary_task_xml(&xml, |path| {
            self.run_checked(
                "create or update the scheduled task",
                &create_or_update_args(path),
            )
        })
    }

    fn start(&self) -> Result<()> {
        match self.inspect_registration()? {
            TaskRegistration::Missing => bail!("Kwiry scheduled task is not installed"),
            TaskRegistration::Foreign => {
                bail!("refusing to start a scheduled task not generated by Kwiry: {TASK_NAME}")
            }
            TaskRegistration::Generated => {}
        }
        let status = self.query_status()?;
        if !status.installed {
            bail!("Kwiry scheduled task is not installed");
        }
        if status.running {
            return Ok(());
        }
        if !status.enabled {
            bail!("Kwiry scheduled task is disabled");
        }
        self.run_checked("start the scheduled task", &run_args())
    }

    fn stop(&self) -> Result<()> {
        match self.inspect_registration()? {
            TaskRegistration::Missing => return Ok(()),
            TaskRegistration::Foreign => {
                bail!("refusing to stop a scheduled task not generated by Kwiry: {TASK_NAME}")
            }
            TaskRegistration::Generated => {}
        }
        let status = self.query_status()?;
        if !status.installed || !status.running {
            return Ok(());
        }
        self.run_checked_allow_absent("stop the scheduled task", &end_args())
    }

    fn restart(&self) -> Result<()> {
        match self.inspect_registration()? {
            TaskRegistration::Missing => bail!("Kwiry scheduled task is not installed"),
            TaskRegistration::Foreign => {
                bail!("refusing to restart a scheduled task not generated by Kwiry: {TASK_NAME}")
            }
            TaskRegistration::Generated => {}
        }
        let status = self.query_status()?;
        if !status.installed {
            bail!("Kwiry scheduled task is not installed");
        }
        if !status.enabled {
            bail!("Kwiry scheduled task is disabled");
        }
        if status.running {
            self.run_checked_allow_absent("stop the scheduled task", &end_args())?;
        }
        self.run_checked("start the scheduled task", &run_args())
    }

    fn status(&self) -> Result<ServiceStatus> {
        self.query_status()
    }

    fn uninstall(&self) -> Result<()> {
        match self.inspect_registration()? {
            TaskRegistration::Missing => return Ok(()),
            TaskRegistration::Foreign => {
                bail!("refusing to remove a scheduled task not generated by Kwiry: {TASK_NAME}")
            }
            TaskRegistration::Generated => {}
        }
        let status = self.query_status()?;
        if !status.installed {
            return Ok(());
        }
        if status.running {
            self.run_checked_allow_absent("stop the scheduled task", &end_args())?;
        }
        self.run_checked_allow_absent("delete the scheduled task", &delete_args())
    }
}

fn task_action_fields(spec: &ServiceSpec) -> Result<(&str, String)> {
    let executable = absolute_path_text(&spec.executable, "executable")?;
    let config = absolute_path_text(&spec.config, "configuration file")?;
    let data_dir = absolute_path_text(&spec.data_dir, "data directory")?;
    let arguments = [
        "--config".to_owned(),
        quote_windows_argument(config),
        "--data-dir".to_owned(),
        quote_windows_argument(data_dir),
        "serve".to_owned(),
    ]
    .join(" ");
    Ok((executable, arguments))
}

pub(crate) fn render_task_xml(spec: &ServiceSpec, sid: &str) -> Result<String> {
    let (executable, arguments) = task_action_fields(spec)?;
    if sid.trim().is_empty() {
        bail!("current-user SID is empty");
    }

    Ok(format!(
        r#"<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>{TASK_MARKER}</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>{sid}</UserId>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>{sid}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>{RESTART_INTERVAL}</Interval>
      <Count>{RESTART_COUNT}</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{executable}</Command>
      <Arguments>{arguments}</Arguments>
    </Exec>
  </Actions>
</Task>
"#,
        sid = xml_escape(sid),
        executable = xml_escape(executable),
        arguments = xml_escape(&arguments),
    ))
}

fn absolute_path_text<'a>(path: &'a Path, label: &str) -> Result<&'a str> {
    let text = path
        .to_str()
        .ok_or_else(|| anyhow!("Kwiry service {label} path is not valid Unicode"))?;
    if !path.is_absolute() && !is_windows_absolute(text) {
        bail!("Kwiry service {label} path must be absolute");
    }
    Ok(text)
}

fn is_windows_absolute(path: &str) -> bool {
    let bytes = path.as_bytes();
    (bytes.len() >= 3
        && bytes[0].is_ascii_alphabetic()
        && bytes[1] == b':'
        && matches!(bytes[2], b'\\' | b'/'))
        || path.starts_with(r"\\")
        || path.starts_with("//")
}

fn xml_escape(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len());
    for character in value.chars() {
        match character {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&apos;"),
            _ => escaped.push(character),
        }
    }
    escaped
}

fn quote_windows_argument(value: &str) -> String {
    let mut quoted = String::with_capacity(value.len() + 2);
    quoted.push('"');
    let mut backslashes = 0;

    for character in value.chars() {
        if character == '\\' {
            backslashes += 1;
            continue;
        }

        if character == '"' {
            quoted.extend(std::iter::repeat_n('\\', backslashes * 2 + 1));
            quoted.push('"');
        } else {
            quoted.extend(std::iter::repeat_n('\\', backslashes));
            quoted.push(character);
        }
        backslashes = 0;
    }

    quoted.extend(std::iter::repeat_n('\\', backslashes * 2));
    quoted.push('"');
    quoted
}

fn with_temporary_task_xml<T>(xml: &str, action: impl FnOnce(&Path) -> Result<T>) -> Result<T> {
    let mut temporary = Builder::new()
        .prefix("kwiry-task-")
        .suffix(".xml")
        .tempfile()
        .context("could not create temporary Task Scheduler XML")?;
    write_utf16le(&mut temporary, xml).context("could not write temporary Task Scheduler XML")?;
    temporary
        .flush()
        .context("could not flush temporary Task Scheduler XML")?;
    action(temporary.path())
}

fn write_utf16le(writer: &mut impl Write, text: &str) -> std::io::Result<()> {
    writer.write_all(&[0xff, 0xfe])?;
    for unit in text.encode_utf16() {
        writer.write_all(&unit.to_le_bytes())?;
    }
    Ok(())
}

